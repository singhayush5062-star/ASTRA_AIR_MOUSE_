def render_params(hw, d):
    lines = ['# Onboard parameters for Vehicle 1',
             '#',
             '# %s' % GENERATED,
             '# Stack: PX4 Pro. Names and values valid on v1.14 (simulation/PX4-Autopilot-v1.14.3)',
             '# and checked against v1.16.1 (flown firmware); px4_fmu-v6x ports TELEM1/TELEM2/GPS2.',
             '# Vehicle: Multi-Rotor. Select the airframe and calibrate sensors/ESCs/RC in',
             '# QGroundControl FIRST, then load this file (it does not set geometry or tuning gains).',
             '#',
             '# Vehicle-Id Component-Id Name Value Type']
    notes = []
    for name, value, ptype, why in px4_params(hw, d):
        val = str(int(value)) if ptype == INT32 else repr(float(value))
        lines.append('1\t1\t%s\t%s\t%d' % (name, val, ptype))
        notes.append('#   %-18s %-10s %s' % (name, val, why))
    return '\n'.join(lines + ['#', '# What each value is for:'] + notes) + '\n'


def render_livox(hw):
    lidar = hw['lidar']
    host, ip = str(lidar['host_ip']), str(lidar['lidar_ip'])
    cfg = {
        'lidar_summary_info': {'lidar_type': 8},
        'MID360': {
            'lidar_net_info': {'cmd_data_port': 56100, 'push_msg_port': 56200,
                               'point_data_port': 56300, 'imu_data_port': 56400,
                               'log_data_port': 56500},
            'host_net_info': {'cmd_data_ip': host, 'cmd_data_port': 56101,
                              'push_msg_ip': host, 'push_msg_port': 56201,
                              'point_data_ip': host, 'point_data_port': 56301,
                              'imu_data_ip': host, 'imu_data_port': 56401,
                              'log_data_ip': '', 'log_data_port': 56501},
        },
        'lidar_configs': [{
            'ip': ip, 'pcl_data_type': 1, 'pattern_mode': 0,
            # Points stay in the LiDAR's own frame: the mount lives in TF/FAST-LIO, not here.
            'extrinsic_parameter': {'roll': 0.0, 'pitch': 0.0, 'yaw': 0.0, 'x': 0, 'y': 0, 'z': 0},
        }],
    }
    return json.dumps(cfg, indent=2) + '\n'


def summary(hw, d):
    lm, rm, cm = d['lidar_mount'], d['rng_mount'], d['cam_mount']
    out = ['Frame chain (base_link = FC IMU, FLU, metres / degrees):',
           '  base_link -> livox_frame  xyz (%.3f, %.3f, %.3f) rpy (%.1f, %.1f, %.1f)'
           % (lm['x'], lm['y'], lm['z'], lm['roll'], lm['pitch'], lm['yaw']),
           '  base_link -> tfmini_link  xyz (%.3f, %.3f, %.3f), beam straight down'
           % (rm['x'], rm['y'], rm['z']),
           '  base_link -> camera_link  xyz (%.3f, %.3f, %.3f) rpy (%.1f, %.1f, %.1f)'
           % (cm['x'], cm['y'], cm['z'], cm['roll'], cm['pitch'], cm['yaw']),
           '  FAST-LIO body (%s IMU) at (%.4f, %.4f, %.4f) in base_link'
           % (d['imu_source'], d['imu_in_base'][0], d['imu_in_base'][1], d['imu_in_base'][2]),
           '  FAST-LIO extrinsic_T %s' % d['ext_T'],
           '  TFmini datum: Z = range + %.4f - %.3f' % (d['tfmini_offset'], d['camera_init_world_z'])]
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='report drift, write nothing')
    ap.add_argument('--config', default=HW_CFG)
    ap.add_argument('--mission-config', default=MISSION_CFG)
    args = ap.parse_args(argv)
    try:
        hw = load(args.config, 'hardware')
        mission = load(args.mission_config, 'nidar')
        d = derive(hw, mission)
    except (ConfigError, KeyError) as e:
        print('hardware.yaml: %s' % e, file=sys.stderr)
        return 2
    outputs = {OUT_FASTLIO: render_fastlio(hw, d), OUT_PARAMS: render_params(hw, d),
               OUT_LIVOX: render_livox(hw)}
    drift = 0
    for path, text in outputs.items():
        rel = os.path.relpath(path, REPO)
        old = None
        if os.path.exists(path):
            with open(path) as f:
                old = f.read()
        if old == text:
            print('  unchanged  %s' % rel)
            continue
        drift += 1
        if args.check:
            print('  STALE      %s' % rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w') as f:
                f.write(text)
            print('  wrote      %s' % rel)
    print(summary(hw, d))
    if args.check and drift:
        print('%d file(s) out of date: run apply_hardware_config.py' % drift, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
