#!/usr/bin/env python3
"""Render the REAL-DRONE files from nidar_config/config/hardware.yaml (+ mission_config.yaml).

    python3 catkin_ws/src/nidar_config/scripts/apply_hardware_config.py          # write
    python3 catkin_ws/src/nidar_config/scripts/apply_hardware_config.py --check  # drift only

Writes (each file carries a GENERATED header; edit hardware.yaml, never these):
    nidar_slam/config/fast_lio/nidar_hw.yaml        FAST-LIO for the Mid-360 + TFmini
    nidar_hardware/config/px4/nidar_hw.params       PX4 parameters, QGroundControl format
                                                    (Parameters -> Tools -> Load from file, or
                                                     rosrun mavros mavparam load <file>)
    nidar_hardware/config/livox/MID360_config.json  livox_ros_driver2 network config

and prints the frame chain it implies, so a wrong sign in a mount is visible before a flight.
Validation refuses combinations that cannot work (e.g. a rotated LiDAR with its own IMU).

Sim-independent: nothing here touches the Gazebo world, the vehicle SDF or the sim FAST-LIO file.
"""
import argparse
import json
import math
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.abspath(os.path.join(HERE, '..', '..'))
REPO = os.path.abspath(os.path.join(SRC, '..', '..'))
HW_CFG = os.path.join(SRC, 'nidar_config', 'config', 'hardware.yaml')
MISSION_CFG = os.path.join(SRC, 'nidar_config', 'config', 'mission_config.yaml')
OUT_FASTLIO = os.path.join(SRC, 'nidar_slam', 'config', 'fast_lio', 'nidar_hw.yaml')
OUT_PARAMS = os.path.join(SRC, 'nidar_hardware', 'config', 'px4', 'nidar_hw.params')
OUT_LIVOX = os.path.join(SRC, 'nidar_hardware', 'config', 'livox', 'MID360_config.json')

# Mid-360 internal IMU position in the LiDAR frame (Livox Mid-360 user manual; FAST-LIO's
# upstream mid360.yaml uses the inverse, the LiDAR in the IMU frame).
MID360_IMU_IN_LIDAR = (0.011, 0.02329, -0.04412)

# PX4 serial port ids (SENS_TFMINI_CFG, MAV_x_CONFIG).
PX4_PORTS = {'TELEM1': 101, 'TELEM2': 102, 'TELEM3': 103, 'TELEM4': 104, 'GPS1': 201,
             'GPS2': 202, 'GPS3': 203}
INT32, REAL32 = 6, 9

GENERATED = 'GENERATED by nidar_config/scripts/apply_hardware_config.py from hardware.yaml -- ' \
            'do not edit; edit hardware.yaml and re-run.'


class ConfigError(Exception):
    pass


def load(path, key):
    with open(path) as f:
        return yaml.safe_load(f)[key]


def rpy_matrix(roll_deg, pitch_deg, yaw_deg):
    """ROS fixed-axis RPY (R = Rz(yaw) Ry(pitch) Rx(roll)), row-major 3x3."""
    r, p, y = (math.radians(v) for v in (roll_deg, pitch_deg, yaw_deg))
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return [[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
            [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
            [-sp, cp * sr, cp * cr]]


def mat_vec(m, v):
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]


def clean(v, nd=5):
    v = round(float(v), nd)
    return 0.0 if v == 0 else v


def mount_of(section, name):
    m = section.get('mount') or {}
    try:
        return {k: float(m.get(k, 0.0)) for k in ('x', 'y', 'z', 'roll', 'pitch', 'yaw')}
    except (TypeError, ValueError):
        raise ConfigError('%s.mount must be numbers {x, y, z, roll, pitch, yaw}' % name)


def derive(hw, mission):
    """Everything the generated files need, validated."""
    lidar, rng, cam, fcu, px4 = hw['lidar'], hw['rangefinder'], hw['camera'], hw['fcu'], hw['px4']
    lm = mount_of(lidar, 'lidar')
    rm = mount_of(rng, 'rangefinder')
    imu_source = str(lidar.get('imu_source', 'livox'))
    if imu_source not in ('livox', 'fcu'):
        raise ConfigError('lidar.imu_source must be livox or fcu, not %r' % imu_source)
    if imu_source == 'livox' and any(abs(lm[k]) > 1e-6 for k in ('roll', 'pitch', 'yaw')):
        raise ConfigError(
            'lidar.imu_source: livox needs the Mid-360 mounted upright and square to the body '
            '(lidar.mount roll = pitch = yaw = 0): FAST-LIO\'s world frame is that IMU\'s frame at '
            'start-up. Mount it square, or set imu_source: fcu (and time_sync: ptp).')
    if imu_source == 'fcu' and lidar.get('time_sync') != 'ptp':
        print('WARNING: imu_source fcu with time_sync %s -- LiDAR and FC IMU stamps come from '
              'different clocks; FAST-LIO needs them aligned to a few ms. Use time_sync: ptp.'
              % lidar.get('time_sync'), file=sys.stderr)
    if rm['z'] >= 0:
        raise ConfigError('rangefinder.mount.z must be NEGATIVE (the TFmini sits below base_link); '
                          'got %.3f' % rm['z'])
    if float(lidar.get('blind', 0)) <= 0:
        raise ConfigError('lidar.blind must be > 0 (propeller/frame self-returns)')
    url = str(fcu.get('url', ''))
    # Onboard UARTs wired to TELEM2 (Jetson ttyTHS*, Pi ttyAMA*/serial0); USB (ttyACM*) has no baud.
    if ':' in url and url.startswith(('/dev/ttyTHS', '/dev/ttyAMA', '/dev/serial0', '/dev/ttyS')):
        baud = int(url.rsplit(':', 1)[1])
        if baud != int(fcu.get('telem2_baud', baud)):
            raise ConfigError('fcu.url baud %d != fcu.telem2_baud %s (PX4 SER_TEL2_BAUD)'
                              % (baud, fcu.get('telem2_baud')))
    if rng.get('source') == 'fcu' and str(rng.get('px4_port', '')).upper() not in PX4_PORTS:
        raise ConfigError('rangefinder.px4_port must be one of %s' % ', '.join(sorted(PX4_PORTS)))

    R = rpy_matrix(lm['roll'], lm['pitch'], lm['yaw'])
    t_mount = [lm['x'], lm['y'], lm['z']]
    if imu_source == 'livox':
        # FAST-LIO body = Mid-360 IMU. extrinsic = LiDAR in that IMU frame (fixed by the device).
        ext_T = [-c for c in MID360_IMU_IN_LIDAR]
        ext_R = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
        imu_in_base = [a + b for a, b in zip(t_mount, mat_vec(R, MID360_IMU_IN_LIDAR))]
        imu_topic = '/nidar/livox/imu'
    else:
        # FAST-LIO body = base_link (PX4 IMU via MAVROS). extrinsic = the LiDAR mount itself.
        ext_T, ext_R, imu_in_base = t_mount, R, [0.0, 0.0, 0.0]
        imu_topic = '/mavros/imu/data'

    pad = mission['launch_pad']
    spawn_z = round(float(pad['thickness']) + float(mission['vehicle']['belly_clearance']), 4)
    return {
        'imu_source': imu_source, 'imu_topic': imu_topic,
        'lidar_mount': lm, 'rng_mount': rm, 'cam_mount': mount_of(cam, 'camera'),
        'ext_T': [clean(v) for v in ext_T],
        'ext_R': [clean(v, 6) for row in ext_R for v in row],
        'imu_in_base': [clean(v) for v in imu_in_base],
        'tfmini_offset': clean(-rm['z'], 4),
        'camera_init_world_z': spawn_z,
        'cruise_alt': float(mission['vehicle'].get('cruise_altitude_world', 1.5)),
        'yaw_rate_deg': math.degrees(float(mission['flight'].get('max_yaw_rate', 1.047))),
    }


def render_fastlio(hw, d):
    lidar, rng = hw['lidar'], hw['rangefinder']
    blind = float(lidar['blind'])
    return '''# %s
# FAST-LIO for the real drone: Livox Mid-360 (CustomMsg via livox_bridge.py) + TFmini Plus.
# Loaded by nidar_slam/launch/nidar_mapping.launch config:=...nidar_hw.yaml (hw_bringup.sh does).
common:
    lid_topic:  "/nidar/livox/lidar"   # livox_bridge.py: driver2 CustomMsg -> FAST-LIO's type
    imu_topic:  "%s"   # imu_source: %s
    time_sync_en: false                # clocks are aligned by livox_bridge.py / PTP instead
    time_offset_lidar_to_imu: 0.0

preprocess:
    lidar_type: 1                      # 1 = Livox CustomMsg (Avia/Mid-360 handler)
    scan_line: 4                       # Mid-360: 4 scan lines
    scan_rate: %d
    timestamp_unit: 3                  # unused for CustomMsg (per-point offset_time is ns)
    blind: %s                          # hardware.yaml lidar.blind: props / arms / legs

mapping:
    acc_cov: 0.1
    gyr_cov: 0.1
    b_acc_cov: 0.0001
    b_gyr_cov: 0.0001
    fov_degree: 360
    det_range: %s
    # Altitude datum: published Z = TFmini range + tfmini_mount_offset - camera_init_world_z.
    # tfmini_mount_offset = -hardware.yaml rangefinder.mount.z (beam origin below base_link).
    # camera_init_world_z is the frame convention shared with the guard, FUEL's world->map TF
    # and the mission manager (mission_config.yaml launch_pad.thickness + vehicle.belly_clearance);
    # it cancels out and must stay equal to theirs, NOT be re-measured on the real vehicle.
    tfmini_mount_offset: %s
    camera_init_world_z: %s
    tfmini_range_min: %s
    tfmini_range_max: %s
    extrinsic_est_en: false
    # LiDAR pose in the IMU frame FAST-LIO integrates (%s).
    extrinsic_T: [ %s ]
    extrinsic_R: [ %s ]

publish:
    path_en:  true
    scan_publish_en:  true
    dense_publish_en: true
    scan_bodyframe_pub_en: true

pcd_save:
    pcd_save_en: false
''' % (GENERATED, d['imu_topic'], d['imu_source'], int(lidar.get('scan_rate_hz', 10)), blind,
       float(lidar.get('det_range', 40.0)), d['tfmini_offset'], d['camera_init_world_z'],
       float(rng.get('range_min', 0.1)), float(rng.get('range_max', 12.0)),
       'Mid-360 internal IMU, fixed by the device' if d['imu_source'] == 'livox'
       else 'PX4 IMU = base_link: the LiDAR mount from hardware.yaml',
       ', '.join(str(v) for v in d['ext_T']),
       ',\n                   '.join(', '.join(str(v) for v in d['ext_R'][i:i + 3]) for i in (0, 3, 6)))


